const byLocale: Record<string, Record<string, string>> = { es: es.codes, en: en.codes }

export function errorCodeMessage(code: unknown, lang: string): string | undefined {
  if (typeof code !== 'string' || !TRANSLATED.has(code)) return undefined
  return (byLocale[lang] ?? byLocale.es)[code]
}

/** Text for an error body read with a plain fetch (outside apiClient), in the page language. */
export function errorBodyMessage(
  data: { code?: unknown; error?: unknown } | null | undefined
): string | undefined {
  const lang = typeof document === 'undefined' ? 'es' : document.documentElement.lang
  const translated = errorCodeMessage(data?.code, lang)
  if (translated) return translated
  return typeof data?.error === 'string' ? data.error : undefined
}
